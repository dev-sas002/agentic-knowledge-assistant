"""
The human-approval gate.

This is the part of the system worth reviewing. A retrieval agent that answers
questions is a search box with better prose; an agent that *changes the
business* — takes a dish off sale, republishes opening hours — is a different
kind of object, and what makes it safe is not the model but this module.

The gate is a state machine with exactly one path to a side effect:

    PENDING ──approve()──▶ EXECUTED        (the only branch that calls out)
       │  │
       │  └─reject()────▶ REJECTED
       └────(ttl)───────▶ EXPIRED

Four properties are deliberate, and each one is a bug that a naïve
implementation has.

**The proposal never carries the destination.** ``approve`` looks the action
type up in ``agents.actions.ACTIONS`` and takes the endpoint from the registry.
Nothing parsed from a query and nothing generated by a model can influence
where a request goes; an unregistered type cannot be approved at all. This is
the structural half of the prompt-injection defence — see
``agents/prompting.py`` for the other half.

**Waiting state lives here, not in the graph and not in the browser.** A
LangGraph invocation is a function call: it returns, and its state is gone. A
Streamlit session is worse — it re-runs the whole script on every widget
interaction, so anything held in a local variable is reconstructed from scratch
several times while a human reads the screen. The gate keeps the pending
request in a store, and the UI holds nothing but its id. Reloading the approval
page therefore shows the same request rather than losing it or creating a
second one.

**Approval is idempotent, and the check happens under the lock.** A
double-clicked "Approve" button produced two requests to the ops API in the
naïve version, because the state transition and the dispatch were not atomic.
Here the transition to ``APPROVING`` happens while holding the lock; the second
click finds a non-pending request and is refused.

**Expiry fails closed, and is re-checked at approval time.** An approval screen
left open overnight must not still be able to change tomorrow's menu. Reads
mark expired requests lazily, but the authoritative check is inside
``approve``, after the lock is taken — otherwise a request can expire between
the render and the click and still go through.

Rejection and expiry are both recorded rather than discarded: "who declined
this, and when" is the question an incident review asks first.
"""

from __future__ import annotations

import logging
import threading
import time
import uuid
from collections.abc import Callable
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Protocol

from agents import config
from agents.actions import ACTIONS, ActionSpec, ProposedAction, Risk

logger = logging.getLogger(__name__)


class ApprovalStatus(str, Enum):
    PENDING = "pending"
    #: Held briefly while the dispatch is in flight, so a second approval of
    #: the same request cannot start a second dispatch.
    APPROVING = "approving"
    EXECUTED = "executed"
    REJECTED = "rejected"
    EXPIRED = "expired"
    #: Approved by a human, but the ops API refused or was unreachable. A
    #: distinct state from REJECTED: the decision was yes, the execution failed.
    FAILED = "failed"

    @property
    def is_terminal(self) -> bool:
        return self is not ApprovalStatus.PENDING and self is not ApprovalStatus.APPROVING


class ApprovalError(RuntimeError):
    """The gate refused a transition."""


class UnknownAction(ApprovalError):
    """An action type that is not in the registry cannot be approved."""


@dataclass
class ApprovalRequest:
    """One proposed change, waiting for a human."""

    id: str
    action_type: str
    params: dict[str, str]
    original_query: str
    requested_by: str
    created_at: float
    expires_at: float
    status: ApprovalStatus = ApprovalStatus.PENDING
    decided_by: str | None = None
    decided_at: float | None = None
    reason: str | None = None
    result: dict[str, Any] | None = None
    error: str | None = None
    history: list[dict[str, Any]] = field(default_factory=list)

    # -- derived ---------------------------------------------------------
    @property
    def spec(self) -> ActionSpec | None:
        return ACTIONS.get(self.action_type)

    @property
    def risk(self) -> Risk:
        spec = self.spec
        return spec.risk if spec else Risk.LOW

    @property
    def summary(self) -> str:
        spec = self.spec
        return spec.describe(self.params) if spec else "Unrecognised action."

    def seconds_remaining(self, now: float | None = None) -> float:
        return max(0.0, self.expires_at - (now if now is not None else time.time()))

    def is_expired(self, now: float | None = None) -> bool:
        return self.seconds_remaining(now) <= 0

    @property
    def is_actionable(self) -> bool:
        return self.status is ApprovalStatus.PENDING and not self.is_expired()

    def note(self, event: str, **extra: Any) -> None:
        self.history.append({"event": event, "at": time.time(), **extra})

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "action_type": self.action_type,
            "params": dict(self.params),
            "original_query": self.original_query,
            "requested_by": self.requested_by,
            "status": self.status.value,
            "risk": self.risk.value,
            "summary": self.summary,
            "created_at": self.created_at,
            "expires_at": self.expires_at,
            "seconds_remaining": round(self.seconds_remaining(), 1),
            "decided_by": self.decided_by,
            "decided_at": self.decided_at,
            "reason": self.reason,
            "result": self.result,
            "error": self.error,
            "history": list(self.history),
        }


# --------------------------------------------------------------------------
# Dispatch
# --------------------------------------------------------------------------
class ActionDispatcher(Protocol):
    """Carries out an approved action. The only component permitted a side effect."""

    def dispatch(self, request: ApprovalRequest, spec: ActionSpec) -> dict[str, Any]: ...


class RecordingDispatcher:
    """Records what it was asked to do and does nothing.

    The default in tests and in the eval harness: the gate's logic is then
    exercised end to end without an ops API, which is what makes "does a
    rejected action send anything?" a testable question.
    """

    def __init__(self) -> None:
        self.dispatched: list[dict[str, Any]] = []

    def dispatch(self, request: ApprovalRequest, spec: ActionSpec) -> dict[str, Any]:
        record = {"endpoint": spec.endpoint, "payload": _payload(request)}
        self.dispatched.append(record)
        return {"ok": True, "dispatched": record}


class OpsApiDispatcher:
    """Posts to the ops API. The endpoint comes from the registry, never from input."""

    def __init__(self, base_url: str | None = None, timeout: float | None = None) -> None:
        self.base_url = (base_url or config.OPS_API_URL).rstrip("/")
        self.timeout = timeout if timeout is not None else config.OPS_REQUEST_TIMEOUT

    def dispatch(self, request: ApprovalRequest, spec: ActionSpec) -> dict[str, Any]:
        # Imported here rather than at module scope so that importing the gate
        # — which the tests and the graph do — does not require `requests`.
        import requests

        response = requests.post(
            f"{self.base_url}{spec.endpoint}",
            json=_payload(request),
            timeout=self.timeout,
        )
        if not response.ok:
            raise ApprovalError(f"Ops API returned {response.status_code}: {response.text[:200]}")
        try:
            return response.json()
        except ValueError:
            return {"ok": True, "body": response.text[:200]}


def _payload(request: ApprovalRequest) -> dict[str, Any]:
    """What the ops API is sent. The approval id travels with it, so the ops
    audit log and the gate's history can be joined after the fact."""
    return {
        "type": request.action_type,
        "operator": request.decided_by or request.requested_by,
        "approval_id": request.id,
        "original_query": request.original_query,
        **request.params,
    }


# --------------------------------------------------------------------------
# Storage
# --------------------------------------------------------------------------
class ApprovalStore(Protocol):
    """Where pending requests live between the proposal and the decision."""

    def put(self, request: ApprovalRequest) -> None: ...
    def get(self, request_id: str) -> ApprovalRequest | None: ...
    def all(self) -> list[ApprovalRequest]: ...
    def delete(self, request_id: str) -> None: ...


class InMemoryApprovalStore:
    """Process-local storage.

    Honest about its limit: a restart loses pending approvals, and a second
    replica does not see the first one's. That is the right trade for a
    single-container demo and the wrong one for a fleet — which is why this is
    a ``Protocol`` with one implementation rather than a dict inside the gate.
    A Redis or Postgres store is a class with four methods.
    """

    def __init__(self, capacity: int = 500) -> None:
        self._items: dict[str, ApprovalRequest] = {}
        self._capacity = capacity

    def put(self, request: ApprovalRequest) -> None:
        self._items[request.id] = request
        # Bounded: a long-lived process that proposes actions all day must not
        # accumulate decided requests forever. Oldest terminal ones go first.
        if len(self._items) > self._capacity:
            for old in sorted(
                (r for r in self._items.values() if r.status.is_terminal),
                key=lambda r: r.created_at,
            )[: len(self._items) - self._capacity]:
                self._items.pop(old.id, None)

    def get(self, request_id: str) -> ApprovalRequest | None:
        return self._items.get(request_id)

    def all(self) -> list[ApprovalRequest]:
        return sorted(self._items.values(), key=lambda r: r.created_at, reverse=True)

    def delete(self, request_id: str) -> None:
        self._items.pop(request_id, None)


# --------------------------------------------------------------------------
# The gate
# --------------------------------------------------------------------------
class ApprovalGate:
    """Holds proposed actions until a human decides, then dispatches at most once."""

    def __init__(
        self,
        store: ApprovalStore | None = None,
        dispatcher: ActionDispatcher | None = None,
        ttl_seconds: float | None = None,
        clock: Callable[[], float] = time.time,
    ) -> None:
        self.store = store or InMemoryApprovalStore()
        self.dispatcher = dispatcher or OpsApiDispatcher()
        self.ttl_seconds = config.APPROVAL_TTL_SECONDS if ttl_seconds is None else ttl_seconds
        self.clock = clock
        self._lock = threading.Lock()

    # -- proposing -------------------------------------------------------
    def submit(self, action: ProposedAction, requested_by: str | None = None) -> ApprovalRequest:
        """Register a proposed action as pending. Nothing is executed."""
        if not action.is_known:
            raise UnknownAction(f"{action.type!r} is not a registered action.")
        now = self.clock()
        request = ApprovalRequest(
            id=uuid.uuid4().hex[:12],
            action_type=action.type,
            params=dict(action.params),
            original_query=action.original_query,
            requested_by=requested_by or config.OPERATOR_NAME,
            created_at=now,
            expires_at=now + self.ttl_seconds,
        )
        request.note("proposed", by=request.requested_by, risk=request.risk.value)
        with self._lock:
            self.store.put(request)
        logger.info("Approval %s proposed: %s", request.id, request.summary)
        return request

    # -- reading ---------------------------------------------------------
    def get(self, request_id: str) -> ApprovalRequest | None:
        """Fetch a request, marking it expired if its TTL has passed."""
        request = self.store.get(request_id)
        if request is None:
            return None
        self._expire_if_due(request)
        return request

    def pending(self) -> list[ApprovalRequest]:
        requests = self.store.all()
        for request in requests:
            self._expire_if_due(request)
        return [r for r in requests if r.status is ApprovalStatus.PENDING]

    def recent(self, limit: int = 20) -> list[ApprovalRequest]:
        requests = self.store.all()
        for request in requests:
            self._expire_if_due(request)
        return requests[:limit]

    def _expire_if_due(self, request: ApprovalRequest) -> None:
        if request.status is ApprovalStatus.PENDING and request.is_expired(self.clock()):
            request.status = ApprovalStatus.EXPIRED
            request.decided_at = self.clock()
            request.reason = f"No decision within {self.ttl_seconds:.0f}s."
            request.note("expired")
            logger.info("Approval %s expired without a decision", request.id)

    # -- deciding --------------------------------------------------------
    def reject(self, request_id: str, decided_by: str | None = None, reason: str = "") -> ApprovalRequest:
        """Decline a pending action. Nothing is sent anywhere."""
        with self._lock:
            request = self._claim(request_id, ApprovalStatus.REJECTED)
            request.decided_by = decided_by or config.OPERATOR_NAME
            request.decided_at = self.clock()
            request.reason = reason or "Rejected by the operator."
            request.note("rejected", by=request.decided_by, reason=request.reason)
            self.store.put(request)
        logger.info("Approval %s rejected by %s", request.id, request.decided_by)
        return request

    def approve(self, request_id: str, decided_by: str | None = None) -> ApprovalRequest:
        """Approve and dispatch. The single path from a proposal to a side effect."""
        with self._lock:
            request = self._claim(request_id, ApprovalStatus.APPROVING)
            request.decided_by = decided_by or config.OPERATOR_NAME
            request.decided_at = self.clock()
            request.note("approved", by=request.decided_by)
            self.store.put(request)

        spec = ACTIONS.get(request.action_type)
        if spec is None:
            # Defensive: `submit` rejects unknown types, so reaching here means
            # the registry changed under a pending request.
            request.status = ApprovalStatus.FAILED
            request.error = f"{request.action_type!r} is no longer a registered action."
            request.note("failed", error=request.error)
            self.store.put(request)
            raise UnknownAction(request.error)

        try:
            result = self.dispatcher.dispatch(request, spec)
        except Exception as exc:
            request.status = ApprovalStatus.FAILED
            request.error = f"{type(exc).__name__}: {exc}"
            request.note("dispatch_failed", error=request.error)
            self.store.put(request)
            logger.exception("Approval %s failed to dispatch", request.id)
            return request

        request.status = ApprovalStatus.EXECUTED
        request.result = result if isinstance(result, dict) else {"result": result}
        request.note("executed", endpoint=spec.endpoint)
        self.store.put(request)
        logger.info("Approval %s executed via %s", request.id, spec.endpoint)
        return request

    def _claim(self, request_id: str, target: ApprovalStatus) -> ApprovalRequest:
        """Transition a request out of PENDING, or explain why it cannot be.

        Called with the lock held. Expiry is re-checked here rather than
        trusted from the render: a request can expire between the screen being
        drawn and the button being clicked.
        """
        request = self.store.get(request_id)
        if request is None:
            raise ApprovalError(f"No approval request {request_id!r}.")
        if request.status is not ApprovalStatus.PENDING:
            raise ApprovalError(
                f"Approval {request_id} is already {request.status.value}; it cannot be {target.value}."
            )
        if request.is_expired(self.clock()):
            self._expire_if_due(request)
            self.store.put(request)
            raise ApprovalError(f"Approval {request_id} expired before a decision was recorded.")
        request.status = target
        return request


_gate: ApprovalGate | None = None


def get_gate() -> ApprovalGate:
    """The process-wide gate."""
    global _gate
    if _gate is None:
        _gate = ApprovalGate()
    return _gate


def set_gate(gate: ApprovalGate | None) -> None:
    """Install a gate (or ``None`` to rebuild). Used by tests and the UI."""
    global _gate
    _gate = gate
